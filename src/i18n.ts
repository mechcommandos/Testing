export type Lang = 'fr' | 'en';
const dicts: Record<Lang, Dict> = { fr, en };
let current: Lang = 'fr';

export function detectLang(): Lang {
  return (navigator.language || 'fr').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}
export function setLang(l: Lang): void {
  current = l;
  document.documentElement.lang = l;
}
export const getLang = (): Lang => current;

type StrKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];
type ListKey = { [K in keyof Dict]: Dict[K] extends string[] ? K : never }[keyof Dict];

export function t(key: StrKey, params?: Record<string, string | number>): string {
  let s: string = dicts[current][key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Variante avec clé dynamique (noms d'objets, missions…). */
export function td(key: string, params?: Record<string, string | number>): string {
  return key in dicts[current] ? t(key as StrKey, params) : key;
}

export function say(key: ListKey): string {
  const list = dicts[current][key];
  return list[Math.floor(Math.random() * list.length)];
}

export function fmt(n: number): string {
  return Math.round(n).toLocaleString(current === 'fr' ? 'fr-FR' : 'en-US');
}

export function fmtDuration(ms: number): string {
  const total = Math.max(0, Math.ceil(ms / 60000));
  const h = Math.floor(total / 60);
  const m = total % 60;
  return h > 0 ? `${h} h ${String(m).padStart(2, '0')}` : `${m} min`;
}
